package ca.pkay.rcloneexplorer.Services;

import android.app.IntentService;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.Intent;
import android.net.Uri;
import androidx.annotation.Nullable;
import androidx.core.app.NotificationCompat;

import java.io.IOException;
import java.net.InetAddress;
import java.net.ServerSocket;
import java.security.GeneralSecurityException;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.List;

import ca.pkay.rcloneexplorer.BroadcastReceivers.ServeCancelAction;
import ca.pkay.rcloneexplorer.Items.RemoteItem;
import ca.pkay.rcloneexplorer.R;
import ca.pkay.rcloneexplorer.Rclone;
import ca.pkay.rcloneexplorer.util.FLog;
import ca.pkay.rcloneexplorer.util.FlagsUtil;
import ca.pkay.rcloneexplorer.util.NotificationUtils;
import ca.pkay.rcloneexplorer.util.ServeTlsHelper;


public class StreamingService extends IntentService {

    private static final String TAG = "StreamingService";
    public static final String SERVE_PATH_ARG = "ca.pkay.rcexplorer.streaming_service.arg1";
    public static final String REMOTE_ARG = "ca.pkay.rcexplorer.streaming_service.arg2";
    public static final String SHOW_NOTIFICATION_TEXT = "ca.pkay.rcexplorer.streaming_service.arg3";
    public static final String SERVE_PORT = "ca.pkay.rcexplorer.streaming_service.arg4";
    public static final String SERVE_BASE_URL = "ca.pkay.rcexplorer.streaming_service.serve_base_url";
    public static final String SERVE_PROTOCOL = "ca.pkay.rcexplorer.serve_protocol";
    public static final String ALLOW_REMOTE_ACCESS = "ca.pkay.rcexplorer.allow_remote_access";
    public static final String ALLOW_WRITE = "ca.pkay.rcexplorer.allow_write";
    public static final String AUTHENTICATION_USERNAME = "ca.pkay.rcexplorer.username";
    public static final String AUTHENTICATION_PASSWORD = "ca.pkay.rcexplorer.password";
    public static final int SERVE_HTTP = 11;
    public static final int SERVE_WEBDAV = 12;
    public static final int SERVE_FTP = 13;
    public static final int SERVE_DLNA = 14;
    private final String CHANNEL_ID = "ca.pkay.rcexplorer.streaming_channel";
    private final String CHANNEL_NAME = "Streaming service";
    private final int PERSISTENT_NOTIFICATION_ID = 179;
    private Rclone rclone;
    private Process runningProcess;
    private ServeTlsHelper.TlsMaterial activeTlsMaterial;
    private volatile boolean stopping;

    /**
     * Creates an IntentService.  Invoked by your subclass's constructor.*
     */
    public StreamingService() {
        super("ca.pkay.rcexplorer.streamingservice");
    }

    @Override
    public void onCreate() {
        super.onCreate();
        setNotificationChannel();
        rclone = new Rclone(this);
    }

    @Override
    protected void onHandleIntent(@Nullable Intent intent) {
        if (intent == null) {
            return;
        }
        final String servePath = intent.getStringExtra(SERVE_PATH_ARG);
        final RemoteItem remote = intent.getParcelableExtra(REMOTE_ARG);
        if (remote == null || servePath == null) {
            return;
        }
        final boolean showNotificationText = intent.getBooleanExtra(SHOW_NOTIFICATION_TEXT, false);
        final int protocol = intent.getIntExtra(SERVE_PROTOCOL, SERVE_HTTP);
        int port = intent.getIntExtra(SERVE_PORT, 0);
        if (port <= 0) {
            try (ServerSocket socket = new ServerSocket(0, 1, InetAddress.getLoopbackAddress())) {
                socket.setReuseAddress(true);
                port = socket.getLocalPort();
            } catch (IOException e) {
                FLog.e(TAG, "onHandleIntent: failed to allocate loopback port", e);
                return;
            }
        }
        final boolean allowRemoteAccess = intent.getBooleanExtra(ALLOW_REMOTE_ACCESS, false);
        final boolean allowWrite = intent.getBooleanExtra(ALLOW_WRITE, false)
                && (protocol == SERVE_WEBDAV || protocol == SERVE_FTP);
        final boolean readOnly = !allowWrite;

        String authenticationUsername = intent.getStringExtra(AUTHENTICATION_USERNAME);
        String authenticationPassword = intent.getStringExtra(AUTHENTICATION_PASSWORD);
        boolean ftpAutoGenerated = false;
        if (protocol == SERVE_FTP) {
            if (authenticationUsername == null || authenticationUsername.trim().isEmpty()
                    || authenticationPassword == null || authenticationPassword.trim().isEmpty()) {
                authenticationUsername = "cloudbridge";
                byte[] passBytes = new byte[16];
                new SecureRandom().nextBytes(passBytes);
                authenticationPassword = android.util.Base64.encodeToString(
                        passBytes, android.util.Base64.NO_WRAP | android.util.Base64.NO_PADDING | android.util.Base64.URL_SAFE);
                ftpAutoGenerated = true;
            }
        }

        String resolvedBaseUrl = intent.getStringExtra(SERVE_BASE_URL);
        boolean hasCredentials = authenticationUsername != null && !authenticationUsername.isEmpty()
                && authenticationPassword != null && !authenticationPassword.isEmpty();
        if ((resolvedBaseUrl == null || resolvedBaseUrl.isEmpty())
                && !hasCredentials
                && (protocol == SERVE_HTTP || protocol == SERVE_WEBDAV)) {
            byte[] tokenBytes = new byte[16];
            new SecureRandom().nextBytes(tokenBytes);
            resolvedBaseUrl = android.util.Base64.encodeToString(
                    tokenBytes, android.util.Base64.NO_WRAP | android.util.Base64.NO_PADDING | android.util.Base64.URL_SAFE);
        }
        final String baseUrl = resolvedBaseUrl;

        ServeTlsHelper.TlsMaterial tlsMaterial = null;
        String lanIp = allowRemoteAccess ? ServeTlsHelper.discoverLanIpv4Address() : null;
        if (allowRemoteAccess && protocol != SERVE_DLNA) {
            try {
                tlsMaterial = ServeTlsHelper.createEphemeralServerTls(getCacheDir(), lanIp);
                activeTlsMaterial = tlsMaterial;
            } catch (GeneralSecurityException | IOException e) {
                FLog.e(TAG, "onHandleIntent: failed to generate TLS certificate for LAN serve", e);
                return;
            }
        }

        int flags = FlagsUtil.Companion.getFlagImmutable();
        Intent foregroundIntent = new Intent(this, ca.pkay.rcloneexplorer.Activities.MainActivity.class);
        PendingIntent pendingIntent = PendingIntent.getActivity(this, 0, foregroundIntent, flags);

        Intent cancelIntent = new Intent(this, ServeCancelAction.class);
        PendingIntent cancelPendingIntent = PendingIntent.getBroadcast(this, 0, cancelIntent, flags);

        NotificationCompat.Builder builder = new NotificationCompat.Builder(this, CHANNEL_ID)
                .setSmallIcon(R.drawable.ic_streaming)
                .setContentTitle(getString(R.string.streaming_service_notification_title))
                .setPriority(NotificationCompat.PRIORITY_LOW)
                .setContentIntent(pendingIntent)
                .addAction(R.drawable.ic_cancel_download, getString(R.string.cancel), cancelPendingIntent);

        List<String> detailLines = new ArrayList<>();
        if (showNotificationText) {
            String scheme = tlsMaterial != null ? "https" : "http";
            String displayHost = (allowRemoteAccess && lanIp != null) ? lanIp : "127.0.0.1";
            if (tlsMaterial != null && (protocol == SERVE_HTTP || protocol == SERVE_WEBDAV)) {
                StringBuilder urlSb = new StringBuilder(scheme).append("://").append(displayHost).append(':').append(port);
                if (baseUrl != null && !baseUrl.isEmpty()) {
                    urlSb.append('/').append(baseUrl);
                }
                String urlText = urlSb.toString();
                builder.setContentText(getString(R.string.streaming_service_notification_tls_url, urlText));
                detailLines.add(getString(R.string.streaming_service_notification_tls_url, urlText));
            } else {
                Uri.Builder uriBuilder = Uri.parse("http://127.0.0.1:" + port).buildUpon();
                if (baseUrl != null && !baseUrl.isEmpty()) {
                    uriBuilder.appendPath(baseUrl);
                }
                Uri uri = uriBuilder.build();
                if (!allowRemoteAccess && (protocol == SERVE_HTTP || protocol == SERVE_WEBDAV)) {
                    Intent webPageIntent = new Intent(Intent.ACTION_VIEW, uri);
                    webPageIntent.setFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_CLEAR_TASK);
                    PendingIntent webPagePendingIntent = PendingIntent.getActivity(this, 0, webPageIntent, flags);
                    builder.setContentIntent(webPagePendingIntent);
                }
                builder.setContentText(getString(R.string.streaming_service_notification_content, port));
                detailLines.add(getString(R.string.streaming_service_notification_content, port));
            }
        }
        if (tlsMaterial != null) {
            detailLines.add(getString(R.string.streaming_service_notification_tls_fingerprint, tlsMaterial.sha256Fingerprint));
        }
        if (ftpAutoGenerated) {
            detailLines.add(getString(R.string.streaming_service_notification_ftp_credentials,
                    authenticationUsername, authenticationPassword));
        }
        if (!detailLines.isEmpty()) {
            builder.setStyle(new NotificationCompat.BigTextStyle().bigText(android.text.TextUtils.join("\n", detailLines)));
        }

        startForeground(PERSISTENT_NOTIFICATION_ID, builder.build());

        try {
            int rcloneProtocol;
            switch (protocol) {
                case SERVE_FTP:
                    rcloneProtocol = Rclone.SERVE_PROTOCOL_FTP;
                    break;
                case SERVE_WEBDAV:
                    rcloneProtocol = Rclone.SERVE_PROTOCOL_WEBDAV;
                    break;
                case SERVE_DLNA:
                    rcloneProtocol = Rclone.SERVE_PROTOCOL_DLNA;
                    break;
                case SERVE_HTTP:
                default:
                    rcloneProtocol = Rclone.SERVE_PROTOCOL_HTTP;
                    break;
            }
            runningProcess = rclone.serve(
                    rcloneProtocol,
                    port,
                    allowRemoteAccess,
                    authenticationUsername,
                    authenticationPassword,
                    remote,
                    servePath,
                    baseUrl,
                    readOnly,
                    tlsMaterial != null ? tlsMaterial.certFile : null,
                    tlsMaterial != null ? tlsMaterial.keyFile : null);

            boolean exitedNormally = false;
            if (runningProcess != null) {
                rclone.collectDiagnostics(runningProcess);
                try {
                    runningProcess.waitFor();
                    exitedNormally = true;
                } catch (InterruptedException e) {
                    FLog.e(TAG, "onHandleIntent: error waiting for process", e);
                }
            }

            if (exitedNormally) {
                if (stopping) rclone.discardDiagnostics(runningProcess);
                else rclone.logErrorOutput(runningProcess);
            }
        } finally {
            if (tlsMaterial != null) {
                tlsMaterial.delete();
                if (activeTlsMaterial == tlsMaterial) {
                    activeTlsMaterial = null;
                }
            }
            stopForeground(true);
        }
    }

    @Override
    public void onDestroy() {
        stopping = true;
        super.onDestroy();
        if (null != runningProcess) {
            runningProcess.destroy();
        }
        if (activeTlsMaterial != null) {
            activeTlsMaterial.delete();
            activeTlsMaterial = null;
        }
        ServeTlsHelper.cleanupTlsDirectory(getCacheDir());
    }

    private void setNotificationChannel() {
        NotificationUtils.createNotificationChannel(this,
                CHANNEL_ID,
                CHANNEL_NAME,
                NotificationManager.IMPORTANCE_LOW,
                getString(R.string.streaming_service_notification_channel_description)
        );
    }
}
